def get_scenario(scenario_id: str) -> dict:
    for s in SCENARIOS:
        if s["id"] == scenario_id:
            return s
    return None


def build_event_from_scenario(scenario: dict) -> RevenueEvent:
    now = datetime.utcnow()
    test_hour = scenario.get("test_hour", 10)
    test_minute = scenario.get("test_minute", 0)
    test_time = now.replace(hour=test_hour, minute=test_minute, second=0, microsecond=0)

    return RevenueEvent(
        id=f"scenario_{scenario['id']}",
        type=scenario["type"],
        customer=Customer(
            id="cust_scenario_001",
            name="Test Customer",
            phone="+919876543210",
            email="test@example.com",
            language_pref="hi",
            opted_out=scenario.get("opted_out", False),
        ),
        amount=scenario["amount"],
        root_cause=scenario["decline_code"],
        decline_code=scenario["decline_code"],
        failed_at=test_time - timedelta(hours=48),
        metadata=TransactionMetadata(
            days_overdue=scenario.get("days_overdue"),
        ),
        retry_count=scenario.get("retry_count", 0),
    )


def get_all_scenarios() -> list[dict]:
    return SCENARIOS


